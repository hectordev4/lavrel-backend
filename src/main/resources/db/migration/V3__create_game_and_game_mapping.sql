CREATE TABLE game (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           varchar(255) NOT NULL,
    cover_image_url varchar(1024),
    created_at      timestamptz  NOT NULL DEFAULT now()
);
ALTER TABLE game ENABLE ROW LEVEL SECURITY;

CREATE TABLE game_mapping (
    id               bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id          bigint       NOT NULL REFERENCES game (id) ON DELETE CASCADE,
    platform         varchar(16)  NOT NULL,
    platform_game_id varchar(128) NOT NULL,
    platform_title   varchar(255),
    CONSTRAINT ck_game_mapping_platform CHECK (platform IN ('STEAM', 'XBOX', 'PSN')),
    CONSTRAINT uq_game_mapping_platform_game_id UNIQUE (platform, platform_game_id)
);
CREATE INDEX idx_game_mapping_game_id ON game_mapping (game_id, platform);
ALTER TABLE game_mapping ENABLE ROW LEVEL SECURITY;
