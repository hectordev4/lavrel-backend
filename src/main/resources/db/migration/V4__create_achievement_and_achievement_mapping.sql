CREATE TABLE achievement (
    id                   bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id              bigint        NOT NULL REFERENCES game (id) ON DELETE CASCADE,
    steam_achievement_id varchar(255)  NOT NULL,
    name                 varchar(255)  NOT NULL,
    description          varchar(2000),
    icon_url             varchar(1024),
    hidden               boolean       NOT NULL DEFAULT false,
    updated_at           timestamptz,
    CONSTRAINT uq_achievement_game_steam_id UNIQUE (game_id, steam_achievement_id)
);
ALTER TABLE achievement ENABLE ROW LEVEL SECURITY;

CREATE TABLE achievement_mapping (
    achievement_id          bigint       NOT NULL REFERENCES achievement (id) ON DELETE CASCADE,
    platform                varchar(16)  NOT NULL,
    platform_achievement_id varchar(128),
    is_available            boolean      NOT NULL,
    PRIMARY KEY (achievement_id, platform),
    CONSTRAINT ck_achievement_mapping_platform CHECK (platform IN ('XBOX', 'PSN')),
    -- An available mapping must point to a platform achievement.
    CONSTRAINT ck_achievement_mapping_available CHECK (NOT is_available OR platform_achievement_id IS NOT NULL)
);
CREATE INDEX idx_achievement_mapping_platform_ach ON achievement_mapping (platform, platform_achievement_id);
ALTER TABLE achievement_mapping ENABLE ROW LEVEL SECURITY;
