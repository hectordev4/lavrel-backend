-- Profile shelves: what a public profile shows beyond its header, chosen and ordered by the user. A COLLECTION shelf
-- points at one of the user's collections (deleting the collection removes the shelf); an ACHIEVEMENTS shelf holds
-- up to 12 hand-picked unlocked achievements, in order.
CREATE TABLE profile_shelf (
    id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     uuid        NOT NULL,
    user_id       bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type          varchar(32) NOT NULL,
    title         varchar(60),
    position      integer     NOT NULL,
    collection_id uuid        REFERENCES collection (public_id) ON DELETE CASCADE,
    created_at    timestamptz NOT NULL,
    CONSTRAINT uq_profile_shelf_public_id UNIQUE (public_id),
    CONSTRAINT ck_profile_shelf_type
        CHECK (type IN ('COLLECTION', 'RECENTLY_PLAYED', 'PLAYING', 'COMPLETED', 'ACHIEVEMENTS', 'STATS')),
    CONSTRAINT ck_profile_shelf_collection CHECK ((type = 'COLLECTION') = (collection_id IS NOT NULL)),
    CONSTRAINT ck_profile_shelf_position CHECK (position >= 1)
);
CREATE INDEX idx_profile_shelf_user ON profile_shelf (user_id, position);
ALTER TABLE profile_shelf ENABLE ROW LEVEL SECURITY;

CREATE TABLE profile_shelf_achievement (
    shelf_id       bigint  NOT NULL REFERENCES profile_shelf (id) ON DELETE CASCADE,
    achievement_id bigint  NOT NULL REFERENCES achievement (id) ON DELETE CASCADE,
    position       integer NOT NULL,
    PRIMARY KEY (shelf_id, achievement_id)
);
ALTER TABLE profile_shelf_achievement ENABLE ROW LEVEL SECURITY;
