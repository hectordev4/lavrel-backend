-- One Fandom (or wiki.gg...) wiki often covers a whole franchise, so wikis are stored once and games are linked to
-- them: reference_wiki holds the wiki (its address and what it says about itself: name, license, license link, where
-- its pages live) and game_wiki links each game to at most one wiki. Replaces assistant_wiki (V26), which repeated
-- the address and license for every game.
CREATE TABLE reference_wiki (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_url     varchar(300) NOT NULL,
    site_name   varchar(200),
    license     varchar(100) NOT NULL,
    license_url varchar(300),
    article_url varchar(300),
    added_at    timestamptz  NOT NULL,
    CONSTRAINT uq_reference_wiki_api_url UNIQUE (api_url)
);
ALTER TABLE reference_wiki ENABLE ROW LEVEL SECURITY;

CREATE TABLE game_wiki (
    game_id  bigint      PRIMARY KEY REFERENCES game (id) ON DELETE CASCADE,
    wiki_id  bigint      NOT NULL REFERENCES reference_wiki (id) ON DELETE CASCADE,
    added_at timestamptz NOT NULL
);
CREATE INDEX idx_game_wiki_wiki ON game_wiki (wiki_id);
ALTER TABLE game_wiki ENABLE ROW LEVEL SECURITY;

-- Existing approvals: each address once (its first license and date), then every game linked to it. Name, license
-- link and page address are filled the next time an admin approves the wiki (the backend reads them from the wiki).
INSERT INTO reference_wiki (api_url, license, added_at)
SELECT api_url, min(license), min(added_at)
FROM assistant_wiki
GROUP BY api_url;

INSERT INTO game_wiki (game_id, wiki_id, added_at)
SELECT a.game_id, w.id, a.added_at
FROM assistant_wiki a
JOIN reference_wiki w ON w.api_url = a.api_url;

DROP TABLE assistant_wiki;
