-- Collections of the user's own games ("Platinum hunt", "Cozy games"). The API uses public_id; names are unique per
-- user ignoring case. A game can be in several collections; only owned games are added (checked by the backend), and
-- a game that leaves the library stays saved here but is hidden until it is owned again.
CREATE TABLE collection (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id  uuid        NOT NULL,
    user_id    bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name       varchar(40) NOT NULL,
    position   integer     NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT uq_collection_public_id UNIQUE (public_id),
    CONSTRAINT ck_collection_position CHECK (position >= 1)
);
CREATE UNIQUE INDEX uq_collection_user_name ON collection (user_id, lower(name));
ALTER TABLE collection ENABLE ROW LEVEL SECURITY;

CREATE TABLE collection_game (
    collection_id bigint      NOT NULL REFERENCES collection (id) ON DELETE CASCADE,
    game_id       bigint      NOT NULL REFERENCES game (id) ON DELETE CASCADE,
    added_at      timestamptz NOT NULL,
    PRIMARY KEY (collection_id, game_id)
);
CREATE INDEX idx_collection_game_game ON collection_game (game_id);
ALTER TABLE collection_game ENABLE ROW LEVEL SECURITY;
