CREATE TABLE platform_account (
    id             bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    platform       varchar(16)  NOT NULL,
    external_id    varchar(128) NOT NULL,
    display_name   varchar(255),
    verified       boolean      NOT NULL DEFAULT false,
    verified_at    timestamptz,
    linked_at      timestamptz  NOT NULL DEFAULT now(),
    last_synced_at timestamptz,
    CONSTRAINT ck_platform_account_platform CHECK (platform IN ('STEAM', 'XBOX', 'PSN')),
    CONSTRAINT ck_platform_account_verified CHECK (NOT verified OR verified_at IS NOT NULL),
    -- The name is referenced by the Java adapter to translate the duplicate-link error.
    CONSTRAINT uq_platform_account_platform_external_id UNIQUE (platform, external_id)
);
CREATE INDEX idx_platform_account_user_id ON platform_account (user_id);
ALTER TABLE platform_account ENABLE ROW LEVEL SECURITY;
