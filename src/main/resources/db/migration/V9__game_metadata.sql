-- Details shown on the game page: release, platforms, reviews, creators (developer, publisher, franchise),
-- tags with their weight, store features (player modes, accessibility, controller support) and age ratings.
-- enriched_at is the "published" marker: a game is only visible after its details were fetched and it passed
-- the content policy. NULL means pending; the admin "enrich" endpoint processes the pending ones.
ALTER TABLE game ADD COLUMN release_date            date;
ALTER TABLE game ADD COLUMN windows                 boolean  NOT NULL DEFAULT false;
ALTER TABLE game ADD COLUMN mac                     boolean  NOT NULL DEFAULT false;
ALTER TABLE game ADD COLUMN linux                   boolean  NOT NULL DEFAULT false;
ALTER TABLE game ADD COLUMN review_count            integer;
ALTER TABLE game ADD COLUMN review_percent_positive smallint;
ALTER TABLE game ADD COLUMN is_free                 boolean  NOT NULL DEFAULT false;
ALTER TABLE game ADD COLUMN required_age            smallint;
ALTER TABLE game ADD COLUMN enriched_at             timestamptz;

CREATE TABLE tag (
    id   bigint       PRIMARY KEY,           -- Steam's own tag id
    name varchar(100) NOT NULL
);
ALTER TABLE tag ENABLE ROW LEVEL SECURITY;

CREATE TABLE game_tag (
    game_id  bigint   NOT NULL REFERENCES game (id) ON DELETE CASCADE,
    tag_id   bigint   NOT NULL REFERENCES tag (id),
    weight   integer  NOT NULL,              -- Steam's vote weight: how strongly users applied the tag
    position smallint NOT NULL,              -- 0 = most applied
    PRIMARY KEY (game_id, tag_id)
);
CREATE INDEX idx_game_tag_tag ON game_tag (tag_id, weight DESC);
ALTER TABLE game_tag ENABLE ROW LEVEL SECURITY;

CREATE TABLE creator (
    id               bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             varchar(255) NOT NULL,
    steam_creator_id bigint,
    CONSTRAINT uq_creator_name UNIQUE (name)
);
ALTER TABLE creator ENABLE ROW LEVEL SECURITY;

CREATE TABLE game_creator (
    game_id    bigint      NOT NULL REFERENCES game (id) ON DELETE CASCADE,
    creator_id bigint      NOT NULL REFERENCES creator (id),
    role       varchar(16) NOT NULL,
    PRIMARY KEY (game_id, creator_id, role),
    CONSTRAINT ck_game_creator_role CHECK (role IN ('DEVELOPER', 'PUBLISHER', 'FRANCHISE'))
);
CREATE INDEX idx_game_creator_creator ON game_creator (creator_id, role);
ALTER TABLE game_creator ENABLE ROW LEVEL SECURITY;

CREATE TABLE feature (
    id         integer      PRIMARY KEY,     -- Steam's own category id (2 = Single-player, 22 = Steam Achievements...)
    name       varchar(100) NOT NULL,
    group_name varchar(16)  NOT NULL,
    CONSTRAINT ck_feature_group CHECK (group_name IN ('PLAYER_MODE', 'FEATURE', 'ACCESSIBILITY', 'CONTROLLER'))
);
ALTER TABLE feature ENABLE ROW LEVEL SECURITY;

CREATE TABLE game_feature (
    game_id    bigint  NOT NULL REFERENCES game (id) ON DELETE CASCADE,
    feature_id integer NOT NULL REFERENCES feature (id),
    PRIMARY KEY (game_id, feature_id)
);
CREATE INDEX idx_game_feature_feature ON game_feature (feature_id);
ALTER TABLE game_feature ENABLE ROW LEVEL SECURITY;

CREATE TABLE game_age_rating (
    game_id     bigint       NOT NULL REFERENCES game (id) ON DELETE CASCADE,
    board       varchar(32)  NOT NULL,       -- esrb, pegi, usk, oflc, cero, kgrb...
    rating      varchar(32)  NOT NULL,
    descriptors varchar(500),                -- one per line
    PRIMARY KEY (game_id, board)
);
ALTER TABLE game_age_rating ENABLE ROW LEVEL SECURITY;

-- The content policy now also reads user tags and age ratings, so games rejected for adult content
-- earlier are judged again with the better data.
DELETE FROM catalog_import_failure WHERE reason LIKE 'adult content%';
